CREATE FUNCTION powerbull_private.es_administrador() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT auth.uid() IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.usuarios WHERE auth_id = (SELECT auth.uid()) AND rol = 'administrador'
  );
$$;
