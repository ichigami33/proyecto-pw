-- Una transacción: valida, bloquea filas en orden, descuenta y registra.
-- El id de solicitud evita descontar dos veces al repetir una petición.
CREATE FUNCTION powerbull_private.comprar(p_items jsonb, p_solicitud uuid) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_usuario bigint; v_total numeric(14,2) := 0; v_pedido public.pedidos%ROWTYPE;
  v_producto public.productos%ROWTYPE; v_item record; v_unidades integer := 0;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Necesitás iniciar sesión para comprar.'; END IF;
  SELECT id INTO v_usuario FROM public.usuarios WHERE auth_id = (SELECT auth.uid());
  IF v_usuario IS NULL THEN RAISE EXCEPTION 'No encontramos tu perfil.'; END IF;
  IF p_solicitud IS NULL THEN RAISE EXCEPTION 'La solicitud de compra no es válida.'; END IF;
  PERFORM pg_advisory_xact_lock(v_usuario);
  SELECT * INTO v_pedido FROM public.pedidos WHERE id = p_solicitud;
  IF FOUND THEN
    IF v_pedido.id_usuario <> v_usuario THEN RAISE EXCEPTION 'La solicitud de compra no es válida.'; END IF;
    RETURN jsonb_build_object('id', v_pedido.id, 'total', v_pedido.total, 'repetida',true);
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 40 THEN
    RAISE EXCEPTION 'El carrito está vacío o tiene demasiados productos.';
  END IF;
  IF EXISTS (SELECT 1 FROM jsonb_to_recordset(p_items) AS x(id bigint,cantidad integer) WHERE id IS NULL OR id < 1 OR cantidad IS NULL OR cantidad NOT BETWEEN 1 AND 99) THEN
    RAISE EXCEPTION 'Revisá las cantidades del carrito.';
  END IF;
  FOR v_item IN SELECT id,sum(cantidad)::integer AS cantidad FROM jsonb_to_recordset(p_items) AS x(id bigint,cantidad integer) GROUP BY id ORDER BY id LOOP
    IF v_item.cantidad > 99 THEN RAISE EXCEPTION 'El máximo es de 99 unidades por producto.'; END IF;
    SELECT * INTO v_producto FROM public.productos WHERE id = v_item.id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Uno de los productos ya no está disponible. Actualizá tu carrito.'; END IF;
    IF v_producto.stock < v_item.cantidad THEN
      RAISE EXCEPTION 'Stock insuficiente para %. Quedan % unidades.',v_producto.nombre,v_producto.stock;
    END IF;
    v_total := v_total + v_producto.precio * v_item.cantidad;
    v_unidades := v_unidades + v_item.cantidad;
  END LOOP;
  INSERT INTO public.pedidos(id,id_usuario,total) VALUES (p_solicitud,v_usuario,v_total);
  FOR v_item IN SELECT id,sum(cantidad)::integer AS cantidad FROM jsonb_to_recordset(p_items) AS x(id bigint,cantidad integer) GROUP BY id ORDER BY id LOOP
    UPDATE public.productos SET stock = stock-v_item.cantidad WHERE id = v_item.id RETURNING * INTO v_producto;
    INSERT INTO public.compras(id_pedido,id_usuario,id_producto,nombre_producto,marca_producto,imagen_producto,cantidad,precio_unitario)
    VALUES(p_solicitud,v_usuario,v_producto.id,v_producto.nombre,v_producto.marca,v_producto.imagen_url,v_item.cantidad,v_producto.precio);
  END LOOP;
  RETURN jsonb_build_object('id',p_solicitud,'total',v_total,'unidades',v_unidades,'repetida',false);
END;
$$;
REVOKE ALL ON FUNCTION powerbull_private.comprar(jsonb,uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION powerbull_private.comprar(jsonb,uuid) TO authenticated;
CREATE FUNCTION public.powerbull_comprar(p_items jsonb, p_solicitud uuid) RETURNS jsonb
