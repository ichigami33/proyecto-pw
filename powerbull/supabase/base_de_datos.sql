CREATE FUNCTION public.powerbull_limite_registro(p_huella text) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE v_intentos integer;
BEGIN
  INSERT INTO powerbull_private.registros_recientes(huella) VALUES(left(p_huella,128))
  ON CONFLICT(huella) DO UPDATE SET
    intentos = CASE WHEN powerbull_private.registros_recientes.inicio < now()-interval '1 hour' THEN 1 ELSE powerbull_private.registros_recientes.intentos+1 END,
    inicio = CASE WHEN powerbull_private.registros_recientes.inicio < now()-interval '1 hour' THEN now() ELSE powerbull_private.registros_recientes.inicio END
  RETURNING intentos INTO v_intentos;
  RETURN v_intentos <= 15;
END;
$$;
REVOKE ALL ON FUNCTION public.powerbull_limite_registro(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.powerbull_limite_registro(text) TO service_role;

